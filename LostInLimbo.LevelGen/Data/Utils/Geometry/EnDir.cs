namespace LostInLimbo.LevelGen.Data.Utils.Geometry;

/// <summary>
/// Represents a direction on a plane. All 8 directions are represented.
/// </summary>
public enum EnDir
{
  /// <summary>North.</summary>
  N,
  /// <summary>North-east.</summary>
  NE,
  /// <summary>East.</summary>
  E,
  /// <summary>South-east.</summary>
  SE,
  /// <summary>South.</summary>
  S,
  /// <summary>South-west.</summary>
  SW,
  /// <summary>West.</summary>
  W,
  /// <summary>North-west.</summary>
  NW,
}